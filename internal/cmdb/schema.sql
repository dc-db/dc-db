-- dc-db PostgreSQL schema.
--
-- Executed once when the database is empty. This project is still in
-- development: change this file and recreate the database (drop the public
-- schema) instead of adding migration files.
--
-- Tables are ordered so that every referenced table exists before the
-- foreign keys that point at it are created.

CREATE TABLE users (
    username TEXT PRIMARY KEY,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin','operator','viewer'))
);

CREATE TABLE people (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 200),
    username TEXT UNIQUE REFERENCES users ON DELETE SET NULL
);

CREATE UNIQUE INDEX people_name_idx ON people (lower(name));

CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 200)
);

CREATE UNIQUE INDEX teams_name_idx ON teams (lower(name));

CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES people ON DELETE CASCADE,
    PRIMARY KEY (team_id, person_id)
);

CREATE INDEX team_members_person_idx ON team_members (person_id);

CREATE TABLE asset_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX asset_groups_name_idx ON asset_groups (lower(name));

CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('host','vm','switch','router','firewall','load_balancer')),
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
    platform TEXT NOT NULL DEFAULT '' CHECK (platform IN ('','pve','kvm')),
    status TEXT NOT NULL DEFAULT 'unknown' CHECK (status IN ('unknown','online','offline','running','stopped','paused')),
    lifecycle TEXT NOT NULL DEFAULT 'active' CHECK (lifecycle IN ('active','retired')),
    owner TEXT NOT NULL DEFAULT '',
    environment TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    probe_enabled BOOLEAN NOT NULL DEFAULT false,
    probe_status TEXT NOT NULL DEFAULT 'unknown' CHECK (probe_status IN ('unknown','reachable','unreachable','error')),
    probe_checked_at TIMESTAMPTZ,
    cpu INTEGER NOT NULL DEFAULT 0 CHECK (cpu >= 0),
    memory_mib INTEGER NOT NULL DEFAULT 0 CHECK (memory_mib >= 0),
    notes TEXT NOT NULL DEFAULT '',
    observed TEXT NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(observed::jsonb) = 'object'),
    source_key TEXT,
    external_key TEXT,
    last_seen_at TIMESTAMPTZ,
    missing_count INTEGER NOT NULL DEFAULT 0,
    group_id BIGINT REFERENCES asset_groups ON DELETE SET NULL,
    team_id BIGINT REFERENCES teams,
    person_id BIGINT REFERENCES people,
    room_id BIGINT,
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_key, external_key),
    CHECK ((source_key IS NULL) = (external_key IS NULL))
);

CREATE INDEX assets_team_idx ON assets (team_id);
CREATE INDEX assets_person_idx ON assets (person_id);
CREATE INDEX assets_kind_name_idx ON assets (kind, lower(name), id);
CREATE INDEX assets_probe_due_idx ON assets (probe_checked_at, id) WHERE probe_enabled AND lifecycle = 'active';

CREATE TABLE asset_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_id BIGINT NOT NULL REFERENCES assets,
    to_id BIGINT NOT NULL REFERENCES assets,
    kind TEXT NOT NULL CHECK (kind IN ('hosts')),
    source_key TEXT,
    UNIQUE (from_id, to_id, kind),
    CHECK (from_id <> to_id)
);

CREATE UNIQUE INDEX asset_links_single_parent_idx
ON asset_links (to_id, kind) WHERE kind = 'hosts';
CREATE INDEX asset_links_to_idx ON asset_links (to_id);

-- Physical or logical ports on an asset. A port can be cabled to exactly one
-- peer port; both sides store the pointer, so the pair is always symmetric.
CREATE TABLE interfaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64),
    medium TEXT NOT NULL DEFAULT 'copper' CHECK (medium IN ('copper','fiber','virtual')),
    speed_mbps INTEGER NOT NULL DEFAULT 0 CHECK (speed_mbps BETWEEN 0 AND 1600000),
    mac TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'up' CHECK (status IN ('up','down','disabled')),
    description TEXT NOT NULL DEFAULT '',
    peer_id BIGINT REFERENCES interfaces ON DELETE SET NULL,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (asset_id, name),
    CHECK (peer_id IS NULL OR peer_id <> id)
);

CREATE INDEX interfaces_asset_idx ON interfaces (asset_id);

-- Optional grouping above data centers (city or region). Rooms may stay
-- ungrouped, so the hierarchy never becomes a prerequisite.
CREATE TABLE regions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    version INTEGER NOT NULL DEFAULT 1
);

CREATE UNIQUE INDEX regions_name_idx ON regions (lower(name));

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id BIGINT REFERENCES regions ON DELETE SET NULL,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
    version INTEGER NOT NULL DEFAULT 1
);

CREATE UNIQUE INDEX rooms_name_idx ON rooms (lower(name));

ALTER TABLE assets ADD CONSTRAINT assets_room_id_fkey FOREIGN KEY (room_id) REFERENCES rooms ON DELETE SET NULL;

CREATE TABLE racks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    zone TEXT NOT NULL DEFAULT '' CHECK (length(zone) <= 40),
    height_u INTEGER NOT NULL CHECK (height_u BETWEEN 1 AND 80),
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE UNIQUE INDEX racks_room_name_idx ON racks (room_id, lower(name));

CREATE TABLE rack_placements (
    asset_id BIGINT PRIMARY KEY REFERENCES assets,
    rack_id BIGINT NOT NULL REFERENCES racks,
    start_u INTEGER NOT NULL CHECK (start_u BETWEEN 1 AND 80),
    units INTEGER NOT NULL CHECK (units BETWEEN 1 AND 80),
    face TEXT NOT NULL DEFAULT 'front' CHECK (face IN ('front','rear')),
    depth TEXT NOT NULL DEFAULT 'full' CHECK (depth IN ('full','half')),
    version INTEGER NOT NULL DEFAULT 1,
    CHECK (start_u + units - 1 <= 80)
);

CREATE INDEX rack_placements_rack_idx ON rack_placements (rack_id, start_u);

CREATE TABLE vlans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vid INTEGER NOT NULL CHECK (vid BETWEEN 1 AND 4094),
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','reserved','deprecated')),
    description TEXT NOT NULL DEFAULT '',
    room_id BIGINT REFERENCES rooms ON DELETE SET NULL,
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX vlans_vid_idx ON vlans (vid);
CREATE UNIQUE INDEX vlans_name_idx ON vlans (lower(name));

CREATE TABLE subnets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
    cidr TEXT NOT NULL UNIQUE,
    gateway TEXT NOT NULL DEFAULT '',
    vlan TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('container','active','reserved','deprecated')),
    role TEXT NOT NULL DEFAULT '',
    room_id BIGINT REFERENCES rooms ON DELETE SET NULL,
    version INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE ip_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subnet_id BIGINT NOT NULL REFERENCES subnets ON DELETE CASCADE,
    ip TEXT NOT NULL,
    asset_id BIGINT REFERENCES assets,
    label TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','reserved','deprecated','dhcp','slaac')),
    dns_name TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT '' CHECK (role IN ('','loopback','secondary','vip','vrrp','hsrp','glbp','anycast')),
    version INTEGER NOT NULL DEFAULT 1,
    UNIQUE (subnet_id, ip)
);

CREATE INDEX ip_allocations_subnet_idx ON ip_allocations (subnet_id, ip);

CREATE TABLE changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT REFERENCES assets,
    asset_name TEXT NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    before_data TEXT,
    after_data TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX changes_asset_id_idx ON changes (asset_id, id DESC);

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    username TEXT NOT NULL REFERENCES users ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX sessions_expires_idx ON sessions (expires_at);

CREATE TABLE asset_service_instances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120)
);
CREATE INDEX asset_service_instances_asset_idx ON asset_service_instances (asset_id, id);

CREATE TABLE metadata_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (length(kind) BETWEEN 1 AND 40),
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 200),
    room_id BIGINT REFERENCES rooms ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX metadata_entries_kind_name_idx ON metadata_entries (kind, lower(name));

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    category TEXT NOT NULL DEFAULT '' CHECK (length(category) <= 40),
    builtin BOOLEAN NOT NULL DEFAULT FALSE,
    port INTEGER CHECK (port IS NULL OR (port BETWEEN 1 AND 65535)),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 300),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX services_name_lower_idx ON services (lower(name));

CREATE TABLE service_projects (
    service_id BIGINT NOT NULL REFERENCES services ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES asset_groups ON DELETE CASCADE,
    PRIMARY KEY (service_id, group_id)
);

CREATE INDEX service_projects_group_idx ON service_projects (group_id);
